DELETE FROM PayWages WHERE PaySlipType = 'WAGES' AND CompCode = @c AND Location = @l AND UnitCode = @u
  AND PCode = @p AND EDate = @t;

INSERT INTO PayWages
  (CompCode, Location, UnitCode, WYear, WMonth, WDay, PCode, EDate, DeptCode, OccpCode,
   TP, RecNo, ECode, EName, Grade, EGroup, SubGroup, DOB, DOJ, Active, RestDay, PaySlipType,
   Work_HR, NS_HR, LayOff_HR, OPF, OESI, OPTax, OHRD_All, CreateDate, PCName)
SELECT e.CompCode, e.Location, @u, YEAR(@f), MONTH(@f), RIGHT(@p, 2), @p, @t,
       IFNULL(a.dept, IFNULL((SELECT x.dept_code FROM ATTEN x WHERE x.WDate <= @t AND x.Work_Type = 'DUTY' AND x.Work_HR > 0
                              AND x.emp_code = e.ECode ORDER BY x.WDate DESC, x.dept_code DESC, x.ocp_code DESC LIMIT 1), '')),
       IFNULL(a.ocp, IFNULL((SELECT x.ocp_code FROM ATTEN x WHERE x.WDate <= @t AND x.Work_Type = 'DUTY' AND x.Work_HR > 0
                             AND x.emp_code = e.ECode ORDER BY x.WDate DESC, x.dept_code DESC, x.ocp_code DESC LIMIT 1), '')),
       '', e.CardNo, e.ECode, e.EName, e.Grade, e.EGroup, e.SubGroup, e.DoB, e.DoJ, e.Active, e.RestDay, 'WAGES',
       IFNULL(a.hr, 0) + IFNULL((SELECT SUM(Adj_HR) FROM PayM_AdjHR WHERE FNEDate = @t AND ECode = e.ECode), 0),
       IFNULL(a.ns, 0), IFNULL(a.lo, 0),
       IFNULL(r.PF, 'N'), IFNULL(r.ESI, 'N'), IFNULL(r.PTax, 'N'), IFNULL(r.HRD, 'N'), NOW(), 'ATTEN & ADJ'
FROM PayOEMP e
LEFT JOIN _w_rate r ON r.ECode = e.ECode AND r.EffDate <= @t
LEFT JOIN _att a ON a.ECode = e.ECode AND a.Work_Type = 'DUTY'
WHERE e.CompCode = @c AND e.Location = @l
  AND e.ECode IN (SELECT emp_code FROM ATTEN WHERE WDate >= @f AND WDate <= @t AND Work_HR > 0 AND Work_Type = 'DUTY'
                  UNION ALL SELECT ECode FROM PayM_Adjustment WHERE FNEDate = @t AND AdjPF > 0
                  UNION ALL SELECT ECode FROM PayJOLeave WHERE DocStatus = 'OPEN' AND FNEDate = @t AND (CL > 0 OR PL > 0))
