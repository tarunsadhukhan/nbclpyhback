   Work_HR, NS_HR, LayOff_HR, OPF, OESI, OPTax, OHRD_All, CreateDate, PCName)
SELECT e.CompCode, e.Location, @u, YEAR(@f), MONTH(@f), RIGHT(@p, 2), @p, @t,
       IFNULL(a.dept, e.DeptCode), IFNULL(a.ocp, e.OcpCode),
       '', e.CardNo, e.ECode, e.EName, e.Grade, e.EGroup, e.SubGroup, e.DoB, e.DoJ, e.Active, e.RestDay, 'WAGES',
       IFNULL(a.hr, 0) + IFNULL((SELECT SUM(Adj_HR) FROM PayM_AdjHR WHERE FNEDate = @t AND ECode = e.ECode), 0),
       IFNULL(a.ns, 0), IFNULL(a.lo, 0),
       IFNULL(r.PF, 'N'), IFNULL(r.ESI, 'N'), IFNULL(r.PTax, 'N'), IFNULL(r.HRD, 'N'), NOW(), 'DUTY Holiday'
FROM PayOEMP e
LEFT JOIN _w_rate r ON r.ECode = e.ECode AND r.EffDate <= @t
