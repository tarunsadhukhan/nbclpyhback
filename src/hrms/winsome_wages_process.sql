CREATE TEMPORARY TABLE _jol (KEY (ECode)) AS
SELECT ECode, SUM(CL) * 8 CL, SUM(PL) * 8 PL, SUM(TotalEarn_CL) TotalEarn_CL, SUM(TotalEarn_PL) TotalEarn_PL
FROM (SELECT FNEDate, ECode, FromDate, ToDate, LeaveDays, CL, PL,
             BasicAmt, BasicInc, DAAmt, TotalEarn TotalEarn_CL, 0.00 b2, 0.00 i2, 0.00 d2, 0.00 TotalEarn_PL,
             PF_833, FPF_167, ESI_0075, TotalDed, 0.00 p2, 0.00 f2, 0.00 e2, 0.00 t2,
             NETPay, ROff, NETPayable, 0.00 n2, 0.00 r2, 0.00 np2
      FROM PayJOLeave WHERE DocStatus = 'OPEN' AND FNEDate = @t AND CL > 0
      UNION
      SELECT FNEDate, ECode, FromDate, ToDate, LeaveDays, CL, PL,
             0.00, 0.00, 0.00, 0.00, BasicAmt, BasicInc, DAAmt, TotalEarn,
             0.00, 0.00, 0.00, 0.00, PF_833, FPF_167, ESI_0075, TotalDed,
             0.00, 0.00, 0.00, NETPay, ROff, NETPayable
      FROM PayJOLeave WHERE DocStatus = 'OPEN' AND FNEDate = @t AND PL > 0) x
GROUP BY FNEDate, ECode;
UPDATE PayWages w JOIN _jol j ON w.ECode = j.ECode SET w.PL_HR = j.PL, w.CL_HR = j.CL
WHERE w.EDate = @t AND w.PaySlipType = 'WAGES';
UPDATE PayWages w JOIN PayOEMP e ON w.ECode = e.ECode SET w.OrgECode = e.ORGECode
WHERE w.EDate = @t AND w.PaySlipType = 'WAGES';
UPDATE PayWages w JOIN _att a ON w.ECode = a.ECode AND a.Work_Type = 'DUTY' AND a.worked > 0
SET w.Work_Day = a.wday
WHERE w.PaySlipType = 'WAGES' AND w.EDate >= '2024-01-01' AND w.PCode = @p AND w.EDate = @t;

