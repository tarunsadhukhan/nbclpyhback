DROP TEMPORARY TABLE IF EXISTS _loanbal;
CREATE TEMPORARY TABLE _loanbal (KEY (ECode)) AS
SELECT ECode, SUM(amt) BalLoan FROM _lparts
WHERE ECode NOT IN (SELECT ECode FROM PayPFFinalOSettlement WHERE DocStatus = 'OPEN')
GROUP BY ECode HAVING SUM(amt) > 0;
UPDATE PayWages w JOIN _loanbal b ON w.ECode = b.ECode JOIN PayOEMP e ON e.ECode = w.ECode AND e.Grade = 'MILL-WORKMEN'
SET w.YTD_LoanAmt = b.BalLoan
WHERE w.CompCode = @c AND w.Location = @l AND w.UnitCode = @u AND w.PCode = @p AND w.EDate = @t AND w.PaySlipType = 'WAGES';
UPDATE PayWages SET UpdatedDate = NOW()
WHERE CompCode = @c AND Location = @l AND UnitCode = @u AND PCode = @p AND EDate = @t;

-- ---------- serial numbers (register / slip order) ---------------------------------------
UPDATE PayWages w JOIN (
    SELECT ECode,
           ROW_NUMBER() OVER (ORDER BY DeptCode, REPLACE(RIGHT(OcpDptSft, 2), '/', ''), EGroup, ECode) SrlNo,
           ROW_NUMBER() OVER (PARTITION BY EGroup ORDER BY DeptCode, REPLACE(RIGHT(OcpDptSft, 2), '/', ''), EGroup, ECode) SlNo
    FROM PayWages WHERE PCode = @p AND PaySlipType = 'WAGES') n ON w.ECode = n.ECode
SET w.SrlNo = n.SrlNo, w.SlNo = n.SlNo
WHERE w.PCode = @p AND w.PaySlipType = 'WAGES';
UPDATE PayWages w JOIN (
    SELECT ECode,
           ROW_NUMBER() OVER (ORDER BY DeptCode, REPLACE(RIGHT(OcpDptSft, 2), '/', ''), EGroup, ECode) SrlNo,
           ROW_NUMBER() OVER (PARTITION BY EGroup ORDER BY DeptCode, REPLACE(RIGHT(OcpDptSft, 2), '/', ''), EGroup, ECode) SlNo
    FROM PayWages WHERE PCode = @p AND PaySlipType = 'OT') n ON w.ECode = n.ECode
SET w.SrlNo = n.SrlNo, w.SlNo = n.SlNo
WHERE w.PCode = @p AND w.PaySlipType = 'OT';

-- ---------- 31/12 only: carry the CL balance into PayLeaveAdj ---------------------------
SET @cy = MAKEDATE(YEAR(@t), 1);
DELETE FROM PayLeaveAdj WHERE MONTH(@t) = 12 AND DAY(@t) = 31 AND YEAR(@t) = YEAR(AdjDate);
INSERT INTO PayLeaveAdj (ECode, AdjDate, PL, CL, ML, CreateDate, UserID, PCName)
SELECT ECode, @t, 0, SUM(ClCL), 0, NOW(), 'AUTO', 'PROCESS-PC'
FROM (SELECT d.ECode, d.ClCL FROM PayLeaveDetails d
      JOIN (SELECT ECode, MAX(EDate) MEDate FROM PayLeaveDetails WHERE EDate <= @t GROUP BY ECode) m
        ON d.ECode = m.ECode AND d.EDate = m.MEDate
      UNION ALL
      SELECT ECode, -1 * SUM(CL) FROM PayJOLeave WHERE FNEDate >= @cy AND FNEDate <= @t GROUP BY ECode
      UNION ALL
      SELECT ECode, -1 * SUM(CL) FROM PayLeaveAdj WHERE AdjDate >= @cy AND AdjDate < @t GROUP BY ECode) x
WHERE MONTH(@t) = 12 AND DAY(@t) = 31
GROUP BY ECode
HAVING SUM(ClCL) <> 0;
