       0, 0, 0, q.QTRLocation, q.QTRNo, q.HRDRate, NOW(), 'PROCESS-PC', 'SYSTEM'
FROM PayOEMP e
JOIN PayOQTR q ON q.ECode = e.ECode
JOIN (SELECT MAX(Sl) MSL FROM PayOQTR GROUP BY QTRLocation, QTRType, QTRNo) m ON q.Sl = m.MSL
