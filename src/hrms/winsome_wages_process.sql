UPDATE PayWages w JOIN _holx h ON w.EDate = h.EDate AND w.ECode = h.ECode SET w.Holiday_HR = h.D
WHERE w.EDate = @t AND w.PaySlipType = 'WAGES';

UPDATE PayWages w JOIN (SELECT ECode, SUM(Work_HR) Work_HR, SUM(NA_HR) NA_HR, SUM(FH_HR) FH_HR
                        FROM PayOMMAttn WHERE EffEDate = @t GROUP BY ECode, EName) m ON w.ECode = m.ECode
SET w.Work_HR = w.Work_HR + m.Work_HR, w.NS_HR = w.NS_HR + m.NA_HR, w.Holiday_HR = w.Holiday_HR + m.FH_HR
WHERE w.EDate = @t AND w.PaySlipType = 'WAGES';

