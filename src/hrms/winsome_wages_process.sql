-- =====================================================================================
-- Winsome FN wages process: MySQL port of the legacy Smart-Eye (Smart_Eye_Jute_Purnasar_Winsome_Live)
-- chain  EXEC SP_WagesProcessing 'WIL','Factory','01',PCode,FromDate,ToDate,LWFAmt
--
--   Daily -> HRALiability -> GetAtten_DUTY -> GetAtten_OT -> GetDailyWages -> GetFNEWages (+ OT_Inc)
--   -> GenInterest_LastEMI -> Cumm -> SrlNo/SlNo -> CL balance adjustment (31/12 only)
--
-- Every table is the legacy one mirrored into the tenant DB under its legacy name
-- (dbqueries/migrations/migrate_payowagesrate_ocp.py); the result lands in `PayWages` (full legacy
-- columns) and src/hrms/winsomeWagesProcess.py copies the period into `paywages`.
--
-- Run by winsomeWagesProcess.run_winsome_wages in ONE session: @c @l @u @p @f @t @lwf are set by the
-- caller. Statements are split on ';' - keep ';' out of string literals and comments.
-- Only the branches live for periods from 01/04/2025 are ported (older date branches are dead code
-- for those periods). ponytail: SP_GenInterest_LastEMI's INSERT is not ported - it only fires for
-- rows with PayWages.PFLoanCap > 0, which the chain sets only up to 31/03/2025 (its DELETE is kept).
-- Not ported either: the ATTEN *_Amt columns of _Daily (no step reads them back).
-- =====================================================================================

SET SESSION div_precision_increment = 30;
SET SESSION sql_mode = REPLACE(@@sql_mode, 'ERROR_FOR_DIVISION_BY_ZERO', '');
SET @pm = LEFT(@p, 7);

-- ---------- SP_WagesProcessing / SP_GenInterest_LastEMI: drop interest generated by an earlier run --
DELETE FROM PayOLoan WHERE FrmName = 'FrmLoanEntry_WIL' AND LoanDate >= @f AND LoanDate <= @t AND LoanType = 'PFINT'
  AND Remarks LIKE 'INTEREST GENERATED VIA WAGES/SALARY PROCESSING%' AND Grade = 'MILL-WORKMEN';

-- latest rate rows on or before the period end (#PayOWagesRate / #PayODARate)
DROP TEMPORARY TABLE IF EXISTS _w_rate;
CREATE TEMPORARY TABLE _w_rate (KEY (ECode)) AS
SELECT r.* FROM PayOWagesRate r
JOIN (SELECT ECode, MAX(EffDate) EffDate FROM PayOWagesRate WHERE EffDate <= @t GROUP BY ECode) m
  ON m.ECode = r.ECode AND m.EffDate = r.EffDate;
DROP TEMPORARY TABLE IF EXISTS _w_da;
CREATE TEMPORARY TABLE _w_da (KEY (ECode)) AS
SELECT r.ECode, r.DA_Amt, r.DA_HR FROM PayODARate r
JOIN (SELECT ECode, MAX(EffDate) EffDate FROM PayODARate WHERE EffDate <= @t GROUP BY ECode) m
  ON m.ECode = r.ECode AND m.EffDate = r.EffDate;
-- second copies: MySQL cannot open one temporary table twice in a statement
DROP TEMPORARY TABLE IF EXISTS _w_rate_pf;
CREATE TEMPORARY TABLE _w_rate_pf (KEY (ECode)) AS SELECT ECode, PF FROM _w_rate;

-- ---------- _Daily: layoff hours into ATTEN --------------------------------------------
UPDATE ATTEN SET LayOff_HR = 0 WHERE WDate >= @f AND WDate <= @t;
UPDATE ATTEN a JOIN Atten_LayOff l
  ON a.WDate = l.WDate AND a.WShift = l.WShift AND a.emp_code = l.ECode AND a.entry_id = l.Entry_ID
SET a.LayOff_HR = l.LayOff_HR
WHERE a.WDate >= @f AND a.WDate <= @t;

-- period attendance per worker and work type (the per-worker sub-selects of _GetAtten_DUTY/_OT)
DROP TEMPORARY TABLE IF EXISTS _att;
CREATE TEMPORARY TABLE _att (KEY (ECode, Work_Type)) AS
SELECT emp_code ECode, UPPER(Work_Type) Work_Type,
       SUM(Work_HR - LayOff_HR + Night_HR) hr,
       SUM(IF(WShift IN ('C', 'C2'), Night_HR, 0)) ns,
       SUM(LayOff_HR) lo,
       MAX(IF(Work_HR > 0, dept_code, NULL)) dept, MAX(IF(Work_HR > 0, ocp_code, NULL)) ocp,
       MAX(dept_code) dept_any, MAX(ocp_code) ocp_any,
       SUM(Work_HR > 0) worked,
       SUM(IF(Work_HR > 0, (Work_HR + Night_HR) / 8.00, 0)) wday
FROM ATTEN WHERE WDate >= @f AND WDate <= @t AND Work_Type IN ('DUTY', 'OT')
GROUP BY emp_code, UPPER(Work_Type);
DROP TEMPORARY TABLE IF EXISTS _att2;
CREATE TEMPORARY TABLE _att2 (KEY (ECode, Work_Type)) AS SELECT * FROM _att;

-- ---------- _HRALiability (2nd fortnight only) ------------------------------------------
