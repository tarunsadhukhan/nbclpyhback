-- ---------- _GetDailyWages: one PayWagesDetails row per day / shift / job ---------------
-- AttendanceReport (legacy view) for the period
DROP TEMPORARY TABLE IF EXISTS _ar;
CREATE TEMPORARY TABLE _ar (KEY (WDate, MainShift, ECode)) AS
SELECT a.WDate, s.DES MainShift, e.ECode, e.EName, o.RateType OCPRateType, a.Work_Type, a.dept_code, a.ocp_code,
       a.Work_HR, a.Night_HR, a.LayOff_HR, a.Job1_code, a.mch1_code
FROM ATTEN a
JOIN PayOEMP e ON a.emp_code = e.ECode
JOIN ODPT o ON a.dept_code = o.DeptCode AND a.ocp_code = o.OCPCode
JOIN Shift s ON a.WShift = s.SHIFTMSTID
JOIN OUNIT u ON a.WUnit = u.UCode
WHERE a.WDate >= @f AND a.WDate <= @t;
DROP TEMPORARY TABLE IF EXISTS _ar2;
CREATE TEMPORARY TABLE _ar2 (KEY (WDate, MainShift, mch1_code)) AS SELECT * FROM _ar;

DELETE FROM PayWagesDetails WHERE WDate >= @f AND WDate <= @t;
INSERT INTO PayWagesDetails (EDate, WDate, MainShift, ECode, EName, DeptCode, DeptName, OcpCode, OcpName, EmpRateType,
                             OCPRateType, Work_Type, Work_HR, NS_HR, Layoff_HR)
SELECT @t, WDate, MainShift, ECode, EName, dept_code, '', ocp_code, '', '', IFNULL(OCPRateType, ''),
       Work_Type, SUM(Work_HR), SUM(Night_HR), SUM(LayOff_HR)
FROM _ar
GROUP BY WDate, MainShift, ECode, EName, OCPRateType, Work_Type, dept_code, ocp_code
ORDER BY ECode, WDate, MainShift, Work_Type;

UPDATE PayWagesDetails d JOIN ODPT o ON d.DeptCode = o.DeptCode AND d.OcpCode = o.OCPCode
SET d.DeptName = o.DeptName, d.OcpName = o.OCPName
WHERE d.WDate >= @f AND d.WDate <= @t;
UPDATE PayWagesDetails d JOIN _ar a ON d.WDate = a.WDate AND d.MainShift = a.MainShift AND d.ECode = a.ECode
SET d.Job1_Code = a.Job1_code
WHERE a.ocp_code IN ('1608', '1609') AND d.EDate = @t;
UPDATE PayWagesDetails d JOIN _w_rate r ON d.ECode = r.ECode
SET d.FBasicRate = r.FBasic, d.FBasic_HR = r.FBasic_HR, d.FBasicIncRate = r.FBasicInc, d.FBasicInc_HR = r.FBasicInc_HR,
    d.EmpRateType = r.RateType, d.DA_All = r.DA_All
WHERE d.EDate = @t;
UPDATE PayWagesDetails d JOIN _w_da r ON d.ECode = r.ECode SET d.DA_Rate = r.DA_Amt, d.DA_HR = r.DA_HR
WHERE d.EDate = @t;

UPDATE PayWagesDetails SET FBasicAmt = (Work_HR - Layoff_HR + NS_HR) * (FBasicRate / FBasic_HR), DAAmt = 0
WHERE EDate = @t AND FBasic_HR > 0;
UPDATE PayWagesDetails SET FBasicIncAmt = (Work_HR - Layoff_HR + NS_HR) * (FBasicIncRate / FBasicInc_HR), DAAmt = 0
WHERE EDate = @t AND FBasicInc_HR > 0;
UPDATE PayWagesDetails SET DAAmt = (Work_HR - Layoff_HR + NS_HR) * (DA_Rate / DA_HR)
WHERE EDate = @t AND DA_All = 'Y' AND DA_HR > 0;

